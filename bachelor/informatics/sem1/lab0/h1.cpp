#include <iostream>
#include <clocale>

using namespace std;

int main() 
{
    // Установка русской локали
    setlocale(LC_ALL, ".65001");

    int N;
    cout << "Введите высоту треугольника (N): ";
    cin >> N;

    // Переменные для количества звездочек (a) и пробелов (b)
    int a = 1;      // В первой строке 1 звездочка
    int b = N - 1;  // В первой строке N-1 пробелов

    cout << "\nТреугольник с прямым углом справа снизу:\n";

    // Внешний цикл (отвечает за строки)
    for (int i = 1; i <= N; i++) 
    {
        // Внутренний цикл 1: печать пробелов (b раз)
        for (int j = 1; j <= b; j++) 
        {
            cout << "  "; // Два пробела для ровности
        }

        // Внутренний цикл 2: печать звездочек (a раз)
        for (int j = 1; j <= a; j++) 
        {
            cout << "* "; // Звездочка с пробелом
        }

        // Переход на новую строку
        cout << endl;

        // Подготовка к следующей строке:
        a++; // Звездочек становится на 1 больше
        b--; // Пробелов становится на 1 меньше
    }

    return 0;
}